/**
 * The help centre: every question about Spendr, and its answer.
 *
 * Two readers, one copy. The app draws it at /help (pages/help, and the
 * desktop's web/pages/WebHelp), and the website publishes it at /help
 * (site/src/pages/help), importing this file at build time - so a question
 * answered here is answered the same way in both, and an answer corrected
 * once is corrected everywhere. Nothing here imports anything, which is what
 * lets the site read it (the same rule as lib/policy.js and lib/changelog.js).
 *
 * ── How an answer is written ──
 *
 * For someone with the app open in their other hand. Plain, warm and specific:
 * what to press, in the words on the screen, and what happens after. Sentence
 * case, no em dashes (`npm run check` fails on them), the app's own names for
 * things (Inflow is "income" in a sentence, but the button says Inflow, so the
 * steps say Inflow). A path through the app is written with › between the
 * names on screen: Settings › Budget limits. Where the phone and a computer
 * differ, say both.
 *
 * ── An article ──
 *
 *   id        stable, kebab-case: it is the address (/help/<id>) on both the
 *             app and the website, and links in from elsewhere use it
 *   topic     one of HELP_TOPICS
 *   title     the question as a person would ask it, or the thing it explains
 *   summary   one sentence: what the answer is, for search results and lists
 *   keywords  other words someone might search with - synonyms, the old name,
 *             the thing it is often confused with
 *   body      blocks, in order:
 *               { p }                  a paragraph
 *               { steps: [...] }       numbered steps, one action each
 *               { tip }                a side note in a box
 *               { shot, caption? }     a screenshot from the website's captures
 *                                      (HELP_SHOTS); `desktop` ones are wide
 *               { go, label }          a button that opens that place in the
 *                                      app (a route, e.g. '/settings/budgets');
 *                                      on the website it opens the app there
 *   related   ids of other articles worth reading next
 *
 * @typedef {{p: string} | {steps: string[]} | {tip: string} | {shot: string, caption?: string} | {go: string, label: string}} HelpBlock
 * @typedef {{id: string, topic: string, title: string, summary: string, keywords?: string[], body: HelpBlock[], related?: string[]}} HelpArticle
 * @typedef {{id: string, title: string, blurb: string, icon: string}} HelpTopic
 */

